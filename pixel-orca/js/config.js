/* ============================================================
   PIXEL ORCA — конфигурация клиента
   ----------------------------------------------------------------
   Этот файл — единственное место, которое нужно править при деплое.
   Он подключается ПЕРВЫМ, до всех игровых скриптов, и не содержит
   ничего, кроме данных, поэтому его можно спокойно переписывать
   скриптом сборки (tools/prepare-pages.mjs) или вручную.

   server — адрес WebSocket-сервера (PaaS-бэкенд):
     • 'wss://my-app.onrender.com/ws'  — боевой режим, живой мультиплеер
     • ''                              — пусто: клиент сам возьмёт /ws
                                         текущего хоста (удобно, когда
                                         фронт и бэк на одном домене)
   Пустое значение НЕ ломает игру: сервер недоступен → честный офлайн
   (офлайн-доход, PvP с ботом, квесты, рыбалка, престиж).
   ============================================================ */
(function (root) {
  'use strict';
  var cfg = {
    /* адрес WebSocket-сервера; см. README «Деплой» */
    server: '',
    /* показывать ли в HUD подпись офлайн-режима (для отладки) */
    debug: false,
    /* включать service worker (офлайн-кэш оболочки). null = решать автоматически:
       включается на https/localhost, выключается в тестах и на file:// */
    serviceWorker: null,
    /* префикс для service worker, если фронт живёт в подпапке (например /SHOOOTERR/) */
    swScope: './'
  };
  root.PO_CONFIG = Object.assign({}, root.PO_CONFIG, cfg);
})(typeof window !== 'undefined' ? window : globalThis);
